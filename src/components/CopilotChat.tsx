import { useQuery } from "@tanstack/react-query";
import { ChevronDown, Database, SearchX, Send, ShieldCheck, Sparkles, Wrench } from "lucide-react";
import { useEffect, useRef, useState } from "react";
import ReactMarkdown from "react-markdown";
import { MiniMap } from "@/components/map";
import { Button } from "@/components/ui/button";
import { Collapsible, CollapsibleContent, CollapsibleTrigger } from "@/components/ui/collapsible";
import { Input } from "@/components/ui/input";
import { Popover, PopoverContent, PopoverTrigger } from "@/components/ui/popover";
import { askCopilot } from "@/lib/api";
import { useApp } from "@/lib/app-context";
import { runQuery } from "@/lib/queries";
import type { CopilotAnswer, Lang } from "@/lib/types";
import { cn } from "@/lib/utils";

const SUGGESTED: Record<Lang, string[]> = {
  en: [
    "Which villages are cut off?",
    "How many buildings were hit within 2 km of the river?",
    "Which bridge failures cut off villages?",
    "Summarize the situation for a field team",
    "What was the rainfall total?",
  ],
  ne: [
    "कुन गाउँहरू काटिएका छन्?",
    "नदीबाट २ कि.मि. भित्र कति भवन प्रभावित?",
    "कुन पुल भत्किँदा गाउँहरू अलग भए?",
    "फिल्ड टोलीका लागि सारांश दिनुहोस्",
  ],
};

type Msg =
  { role: "user"; text: string } | { role: "bot"; answer: CopilotAnswer } | { role: "pending" };

export function CopilotChat() {
  const { lang: appLang } = useApp();
  const [lang, setLang] = useState<Lang>(appLang);
  const [msgs, setMsgs] = useState<Msg[]>([]);
  const [q, setQ] = useState("");
  const end = useRef<HTMLDivElement>(null);
  useEffect(() => {
    setLang(appLang);
  }, [appLang]);
  useEffect(() => {
    end.current?.scrollIntoView({ behavior: "smooth" });
  }, [msgs]);

  async function ask(text: string) {
    if (!text.trim()) return;
    setQ("");
    setMsgs((m) => [...m, { role: "user", text }, { role: "pending" }]);
    const answer = await askCopilot(text, lang);
    setMsgs((m) => [...m.filter((x) => x.role !== "pending"), { role: "bot", answer }]);
  }

  return (
    <div className="grid h-[calc(100vh-5.5rem)] grid-cols-[300px_1fr]">
      <aside className="border-r bg-card p-4">
        <h2 className="mb-3 text-xs font-semibold uppercase tracking-wider text-muted-foreground">
          Suggested questions
        </h2>
        <ul className="space-y-2">
          {SUGGESTED[lang].map((s) => (
            <li key={s}>
              <button
                onClick={() => ask(s)}
                className="w-full rounded-lg border bg-background p-3 text-left text-sm hover:border-primary/50"
              >
                {s}
              </button>
            </li>
          ))}
        </ul>
      </aside>
      <section className="flex min-h-0 flex-col">
        <div className="flex items-center gap-3 border-b px-5 py-3">
          <Sparkles className="size-4 text-primary" />
          <h1 className="text-sm font-semibold">Copilot</h1>
          <span className="flex items-center gap-1.5 rounded border border-border bg-secondary px-2.5 py-1 text-[11px] text-muted-foreground">
            <ShieldCheck className="size-3.5" /> Numbers come from the system's maps, never
            generated by the language model.
          </span>
          <div
            className="ml-auto flex rounded-md border p-0.5 text-xs"
            role="group"
            aria-label="Answer language"
          >
            {(["en", "ne"] as const).map((l) => (
              <button
                key={l}
                onClick={() => setLang(l)}
                aria-pressed={lang === l}
                className={cn(
                  "rounded px-2.5 py-1",
                  lang === l ? "bg-secondary" : "text-muted-foreground",
                )}
              >
                {l === "en" ? "EN" : "नेपाली"}
              </button>
            ))}
          </div>
        </div>
        <div className="panel-scroll flex-1 space-y-5 overflow-y-auto p-6">
          {msgs.length === 0 && (
            <div className="mx-auto mt-16 max-w-md text-center text-sm text-muted-foreground">
              Ask about flooded areas, damaged infrastructure or cut-off villages. Click any blue
              number to see exactly where it came from.
            </div>
          )}
          {msgs.map((m, i) =>
            m.role === "user" ? (
              <div
                key={i}
                className="ml-auto max-w-[70%] rounded-2xl rounded-br-sm bg-primary px-4 py-2.5 text-sm text-primary-foreground"
              >
                {m.text}
              </div>
            ) : m.role === "pending" ? (
              <div key={i} className="flex gap-1 px-2">
                {[0, 1, 2].map((d) => (
                  <span
                    key={d}
                    className="size-2 animate-bounce rounded-full bg-muted-foreground"
                    style={{ animationDelay: `${d * 120}ms` }}
                  />
                ))}
              </div>
            ) : (
              <Answer key={i} a={m.answer} />
            ),
          )}
          <div ref={end} />
        </div>
        <form
          onSubmit={(e) => {
            e.preventDefault();
            ask(q);
          }}
          className="flex gap-2 border-t p-4"
        >
          <Input
            value={q}
            onChange={(e) => setQ(e.target.value)}
            placeholder={lang === "en" ? "Ask about this analysis…" : "यस विश्लेषणबारे सोध्नुहोस्…"}
          />
          <Button type="submit" aria-label="Send">
            <Send className="size-4" />
          </Button>
        </form>
      </section>
    </div>
  );
}

function Answer({ a }: { a: CopilotAnswer }) {
  const { theme } = useApp();
  const { data: run } = useQuery(runQuery);
  if (!a.available) {
    return (
      <div className="max-w-[80%] rounded-2xl rounded-bl-sm border border-dashed border-muted-foreground/40 bg-card p-4">
        <div className="mb-1 flex items-center gap-2 text-sm font-medium">
          <SearchX className="size-4 text-muted-foreground" /> Not available in this analysis
        </div>
        <p className="text-sm text-muted-foreground">{a.markdown}</p>
        {a.note && (
          <p className="mt-2 rounded border border-amber-400/40 bg-amber-50 px-2 py-1 text-[11px] text-amber-700 dark:bg-amber-900/20 dark:text-amber-300">
            {a.note}
          </p>
        )}
        <Tools tools={a.tools} />
      </div>
    );
  }
  return (
    <div className="max-w-[80%] space-y-3 rounded-2xl rounded-bl-sm border bg-card p-4 text-sm">
      <div className="space-y-2 [&_blockquote]:border-l-2 [&_blockquote]:pl-3 [&_blockquote]:text-muted-foreground [&_ol]:list-decimal [&_ol]:pl-5 [&_ul]:list-disc [&_ul]:pl-5">
        <ReactMarkdown
          components={{
            code: ({ children }) => {
              const key = String(children).replace(/^#/, "");
              const s = a.sources[key];
              return s ? <NumberChip s={s} /> : <code>{children}</code>;
            },
          }}
        >
          {a.markdown}
        </ReactMarkdown>
      </div>
      {a.note && (
        <div className="rounded border border-amber-400/40 bg-amber-50 px-2 py-1.5 text-[11px] text-amber-700 dark:bg-amber-900/20 dark:text-amber-300">
          {a.note}
        </div>
      )}
      {a.table && (
        <div className="overflow-hidden rounded-lg border">
          <table className="w-full text-xs">
            <thead className="bg-secondary text-left text-muted-foreground">
              <tr>
                {a.table.columns.map((c) => (
                  <th key={c} className="px-2 py-1.5 font-medium">
                    {c}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {a.table.rows.map((r, i) => (
                <tr key={i} className="border-t">
                  {r.map((c, j) => (
                    <td key={j} className={cn("px-2 py-1.5", typeof c === "number" && "num")}>
                      {c}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
      {a.miniMap && run && (
        <MiniMap run={run} villageIds={a.miniMap.villageIds} dark={theme === "dark"} />
      )}
      <Tools tools={a.tools} />
    </div>
  );
}

function NumberChip({ s }: { s: CopilotAnswer["sources"][string] }) {
  return (
    <Popover>
      <PopoverTrigger asChild>
        <button className="num rounded bg-secondary px-1 font-semibold text-foreground underline decoration-foreground/30 underline-offset-2 hover:bg-accent">
          {s.display}
        </button>
      </PopoverTrigger>
      <PopoverContent className="w-72 text-xs">
        <div className="mb-2 flex items-center gap-1.5 font-semibold">
          <Database className="size-3.5 text-muted-foreground" /> Source
        </div>
        <dl className="grid grid-cols-[60px_1fr] gap-y-1">
          <dt className="text-muted-foreground">Layer</dt>
          <dd className="num">{s.layer}</dd>
          <dt className="text-muted-foreground">Query</dt>
          <dd className="num break-all">{s.query}</dd>
          <dt className="text-muted-foreground">Value</dt>
          <dd className="num">{s.value}</dd>
          <dt className="text-muted-foreground">Run</dt>
          <dd className="num break-all">{s.runId}</dd>
        </dl>
      </PopoverContent>
    </Popover>
  );
}

function Tools({ tools }: { tools: string[] }) {
  return (
    <Collapsible>
      <CollapsibleTrigger className="group flex items-center gap-1 text-[11px] text-muted-foreground hover:text-foreground">
        <Wrench className="size-3" /> Tools used ({tools.length}){" "}
        <ChevronDown className="size-3 transition-transform group-data-[state=open]:rotate-180" />
      </CollapsibleTrigger>
      <CollapsibleContent className="mt-1.5 space-y-1">
        {tools.map((t) => (
          <div key={t} className="num rounded bg-secondary px-2 py-1 text-[11px]">
            {t}
          </div>
        ))}
      </CollapsibleContent>
    </Collapsible>
  );
}
